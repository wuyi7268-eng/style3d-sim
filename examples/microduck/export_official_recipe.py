"""Export with microduck_rl-develop/.venv/bin/python; does not import mjlab at runtime."""

import ast
import dataclasses
import hashlib
import json
import subprocess
from pathlib import Path

from mjlab.tasks.registry import load_env_cfg


def encode(x):
    if isinstance(x, slice):
        return {"slice": [x.start, x.stop, x.step]}
    if dataclasses.is_dataclass(x):
        return {f.name: encode(getattr(x, f.name)) for f in dataclasses.fields(x)}
    if isinstance(x, dict):
        return {str(k): encode(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [encode(v) for v in x]
    if callable(x):
        return x.__module__ + "." + x.__name__
    if x is None or isinstance(x, (str, int, float, bool)):
        return x
    return repr(x)


def main():
    root = Path(__file__).resolve().parent
    source = root / "microduck_rl-develop/src/mjlab_microduck/tasks/mdp.py"
    tree = ast.parse(source.read_text())
    nodes = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    names = {
        "body_pose_tracking_locomotion",
        "body_pose_tracking_6d",
        "phase_pose_blend",
        "phase_rise_gate",
        "_gp_phase",
        "_servo_joint_ids",
        "_servo_joint_pos",
        "_servo_joint_vel",
        "_servo_default_joint_pos",
        "_fallen_mask",
        "_fallen_scale",
        "upright_progress",
        "height_progress",
        "fallen_state_penalty",
        "recovery_success",
        "servo_stall_penalty",
        "servo_acc_spike_penalty",
        "action_rate_l2_fallen_scaled",
        "joint_torque_rate_l2_fallen_scaled",
        "joint_torque_rate_l2",
        "joint_torques_l2",
        "neck_action_rate_l2",
        "pose_target_match",
        "height_target_gaussian",
        "trunk_vertical_accel_penalty",
        "mouth_ground_proximity_phased",
        "mouth_perpendicular_phased",
        "ground_pick_return_pose_phased",
        "ground_pick_return_upright_phased",
        "neck_vel_descent_penalty",
        "_ball_kick_dir",
        "ball_forward_velocity",
        "ball_speed_overshoot_penalty",
        "track_yaw_rate_fine",
        "upright_body_cmd_relative",
        "head_pose_tracking",
        "head_pose_bias_penalty",
        "com_upward_velocity",
        "feet_grounded_reward",
        "single_foot_grounded_reward",
    }
    header = "\n".join(  # noqa: FLY002 -- Keep generated imports readable.
        [
            '"""Selected upstream formulas; generated by export_official_recipe.py. Do not edit."""',
            "# Preserve upstream annotations and defaults for AST provenance checks.",
            "# ruff: noqa: UP037, UP045, B008",
            "from __future__ import annotations",
            "",
            "import math",
            "from typing import Any, Optional",
            "",
            "import torch",
            "",
            "from .official_adapter import SceneEntityCfg, quat_apply_inverse, wrap_to_pi",
            "ManagerBasedRlEnv = Entity = RewardTermCfg = Any",
            '_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")',
            '_NECK_JOINT_PATTERNS = [r".*neck_pitch.*", r".*head_pitch.*", r".*head_yaw.*", r".*head_roll.*"]',
            "",
        ]
    )
    # Snapshot bodies instead of importing mjlab's incompatible Torch/Warp environment.
    (root / "official_reward_functions.py").write_text(
        header + "\n\n".join(ast.unparse(nodes[n]) for n in sorted(names)) + "\n"
    )

    reset_names = {
        "_servo_joint_ids",
        "_env_origin_z",
        "set_random_prone_orientation",
        "set_random_ground_state",
        "set_random_crouch_state",
        "randomize_servo_joints_uniform",
        "maybe_set_random_prone_orientation",
        "_uniform_random_quat",
        "fallen_too_long",
        "_fallen_mask",
    }
    reset_nodes = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in reset_names:
            reset_nodes.append(ast.unparse(node))
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "_CROUCH_ANCHOR_BY_NAME" for target in node.targets
        ):
            reset_nodes.append(ast.unparse(node))
    reset_header = '''"""Upstream reset and termination formulas; generated from the bundled mdp.py."""
# ruff: noqa: F841, UP037, UP045, B008
from __future__ import annotations
import math
from typing import Any, Optional
import numpy as np
import torch
from .official_adapter import SceneEntityCfg
ManagerBasedRlEnv = Entity = Any
_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")

'''
    (root / "official_reset_functions.py").write_text(reset_header + "\n\n".join(reset_nodes) + "\n")

    template_source = Path(__import__("mjlab").__file__).parent / "tasks/velocity/mdp/rewards.py"
    template_tree = ast.parse(template_source.read_text())
    template_names = {
        "angular_momentum_penalty",
        "feet_air_time",
        "feet_clearance",
        "feet_swing_height",
        "feet_slip",
        "self_collision_cost",
    }
    template_nodes = {n.name: n for n in template_tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    template_header = '''"""Upstream mjlab velocity rewards; generated, do not edit."""
from __future__ import annotations
from typing import Any
import torch
from .official_adapter import SceneEntityCfg
from .official_sensors import TerrainHeightSensor
ManagerBasedRlEnv = Entity = RewardTermCfg = ContactSensor = BuiltinSensor = Any
_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")

'''
    (root / "official_velocity_rewards.py").write_text(
        template_header + "\n\n".join(ast.unparse(template_nodes[n]) for n in sorted(template_names)) + "\n"
    )

    out = {
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "velocity_rewards_sha256": hashlib.sha256(template_source.read_bytes()).hexdigest(),
        "tasks": {},
    }
    for task in ["Velocity", "VelStand", "GroundPick", "BallKick"]:
        c = load_env_cfg(f"Mjlab-{task}-Flat-MicroDuck")
        out["tasks"][task.lower()] = {
            "episode_length_s": c.episode_length_s,
            "simulation": encode(c.sim),
            "decimation": c.decimation,
            "actions": encode(c.actions),
            "observations": encode(c.observations),
            "events": encode(c.events),
            "terminations": encode(c.terminations),
            "rewards": encode(c.rewards),
            "curricula": encode(c.curriculum),
            "commands": encode(c.commands),
        }
    (root / "configs/official_snapshot.json").write_text(json.dumps(out, indent=2) + "\n")

    # Formatting uses the parent project's pinned tool, independent of mjlab's environment.
    subprocess.run(
        [
            str(root.parents[1] / ".venv/bin/ruff"),
            "check",
            "--select",
            "I",
            "--fix",
            str(root / "official_velocity_rewards.py"),
            str(root / "official_reset_functions.py"),
        ],
        check=True,
    )
    subprocess.run(
        [
            str(root.parents[1] / ".venv/bin/ruff"),
            "format",
            "--line-length",
            "128",
            str(root / "official_reward_functions.py"),
            str(root / "official_velocity_rewards.py"),
            str(root / "official_reset_functions.py"),
        ],
        check=True,
    )


if __name__ == "__main__":
    main()
