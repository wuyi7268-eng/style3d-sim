def encode(x):
    if isinstance(x, slice):
        return {"slice": [x.start, x.stop, x.step]}
    if dataclasses.is_dataclass(x):
        return {f.name: encode(getattr(x, f.name)) for f in dataclasses.fields(x)}
    if isinstance(x, dict):
        return {str(k): encode(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [encode(v) for v in x]
    if callable(x):
        return x.__module__ + "." + x.__name__
    if x is None or isinstance(x, (str, int, float, bool)):
        return x
    return repr(x)


def preserve_local_terms(exported, previous):
    # Preserve intentional local rewards, curricula, and command sampling when refreshing upstream data.
    for task, spec in exported["tasks"].items():
        old = previous.get("tasks", {}).get(task, {})
        if "terrain_overrides" in old:
            spec["terrain_overrides"] = old["terrain_overrides"]
        for section in ("rewards", "curricula", "commands"):
            for name, term in old.get(section, {}).items():
                if term.get("local") is True:
                    spec.setdefault(section, {})[name] = term


def export_recipe():
    from mjlab.tasks.registry import list_tasks, load_env_cfg, load_rl_cfg

    root = Path(__file__).resolve().parent
    source = root / "microduck_rl-develop/src/mjlab_microduck/tasks/mdp.py"
    tree = ast.parse(source.read_text())
    nodes = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    names = {
        "body_pose_tracking_locomotion",
        "body_pose_tracking_6d",
        "phase_pose_blend",
        "phase_rise_gate",
        "_gp_phase",
        "_servo_joint_ids",
        "_servo_joint_pos",
        "_servo_joint_vel",
        "_servo_default_joint_pos",
        "_fallen_mask",
        "_fallen_scale",
        "upright_progress",
        "height_progress",
        "fallen_state_penalty",
        "recovery_success",
        "servo_stall_penalty",
        "servo_acc_spike_penalty",
        "action_rate_l2_fallen_scaled",
        "joint_torque_rate_l2_fallen_scaled",
        "joint_torque_rate_l2",
        "joint_torques_l2",
        "neck_action_rate_l2",
        "pose_target_match",
        "height_target_gaussian",
        "trunk_vertical_accel_penalty",
        "mouth_ground_proximity_phased",
        "mouth_perpendicular_phased",
        "ground_pick_return_pose_phased",
        "ground_pick_return_upright_phased",
        "neck_vel_descent_penalty",
        "_ball_kick_dir",
        "ball_forward_velocity",
        "ball_speed_overshoot_penalty",
        "track_yaw_rate_fine",
        "upright_body_cmd_relative",
        "head_pose_tracking",
        "head_pose_bias_penalty",
        "com_upward_velocity",
        "feet_grounded_reward",
        "single_foot_grounded_reward",
    }
    # Include every registered task's reward dependency closure, keeping upstream bodies intact.
    configs = {task: load_env_cfg(task) for task in list_tasks() if "MicroDuck" in task}
    excluded = {
        "body_impact_cost",
        "apply_mouth_payload_force",
        "feet_flat_penalty",
        "feet_air_time_upright",
        "variable_posture",
        "variable_posture_body_relaxed",
    }
    names.update(
        term.func.__name__
        for cfg in configs.values()
        for term in cfg.rewards.values()
        if term.func.__name__ in nodes and term.func.__name__ not in excluded
    )
    while True:
        dependencies = {n.id for name in names for n in ast.walk(nodes[name]) if isinstance(n, ast.Name)} & nodes.keys()
        if dependencies <= names:
            break
        names.update(dependencies)
    constants = []
    used = {n.id for name in names for n in ast.walk(nodes[name]) if isinstance(n, ast.Name)}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id in used for t in node.targets)
            and all(isinstance(t, ast.Name) and (t.id.isupper() or t.id.startswith("SPIN_")) for t in node.targets)
        ):
            constants.append(ast.unparse(node))
    header = "\n".join(  # noqa: FLY002 -- Keep generated imports readable.
        [
            '"""Selected upstream formulas; generated by export_recipe.py. Do not edit."""',
            "# Preserve upstream annotations and defaults for AST provenance checks.",
            "# ruff: noqa: UP037, UP045, B008",
            "from __future__ import annotations",
            "",
            "import math",
            "from typing import Any, Optional",
            "",
            "import torch",
            "",
            "from . import velocity_rewards",
            "from .adapter import SceneEntityCfg, quat_apply_inverse, wrap_to_pi",
            "ManagerBasedRlEnv = Entity = RewardTermCfg = Any",
            '_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")',
            '_NECK_JOINT_PATTERNS = [r".*neck_pitch.*", r".*head_pitch.*", r".*head_yaw.*", r".*head_roll.*"]',
            "",
        ]
    )
    # Snapshot bodies instead of importing mjlab's incompatible Torch/Warp environment.
    # Keep local MicroDuck rewards in this same module when refreshing the generated upstream formulas.
    reward_path = root / "reward_functions.py"
    marker = "\n# --- Local MicroDuck rewards (preserved by export_recipe.py) ---\n"
    previous = reward_path.read_text() if reward_path.exists() else ""
    local_tail = previous[previous.index(marker):] if marker in previous else ""
    generated = header + "\n".join(constants) + "\n\n" + "\n\n".join(
        ast.unparse(nodes[n]) for n in sorted(names)
    ) + "\n"
    generated = generated.replace("from mjlab.sensor import ContactSensor", "from .sensors import ContactSensor")
    # Keep readers from importing a partially written generated module while an
    # export is in progress.  A replay/training process may start concurrently.
    temporary = reward_path.with_name(f".{reward_path.name}.tmp")
    temporary.write_text(generated + local_tail)
    os.replace(temporary, reward_path)

    reset_names = {
        "_servo_joint_ids",
        "_env_origin_z",
        "set_random_prone_orientation",
        "set_random_ground_state",
        "set_random_crouch_state",
        "randomize_servo_joints_uniform",
        "maybe_set_random_prone_orientation",
        "_uniform_random_quat",
        "fallen_too_long",
        "_fallen_mask",
        "reset_roulade_state",
        "_roulade_state",
        "reset_rolling_entry",
        "reset_with_forward_velocity",
    }
    reset_nodes = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in reset_names:
            reset_nodes.append(ast.unparse(node))
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "_CROUCH_ANCHOR_BY_NAME" for target in node.targets
        ):
            reset_nodes.append(ast.unparse(node))
    reset_header = '''"""Upstream reset and termination formulas; generated from the bundled mdp.py."""
# ruff: noqa: F841, UP037, UP045, B008
from __future__ import annotations
import math
from typing import Any, Optional
import numpy as np
import torch
from .adapter import SceneEntityCfg
ManagerBasedRlEnv = Entity = Any
_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")

'''
    (root / "reset_functions.py").write_text(
        reset_header + "_ROULADE_FWD_SIGN = 1.0\n\n" + "\n\n".join(reset_nodes) + "\n"
    )

    template_source = Path(__import__("mjlab").__file__).parent / "tasks/velocity/mdp/rewards.py"
    template_tree = ast.parse(template_source.read_text())
    template_names = {
        "angular_momentum_penalty",
        "feet_air_time",
        "feet_clearance",
        "feet_swing_height",
        "feet_slip",
        "self_collision_cost",
    }
    template_nodes = {n.name: n for n in template_tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    template_header = '''"""Upstream mjlab velocity rewards; generated, do not edit."""
from __future__ import annotations
from typing import Any
import torch
from .adapter import SceneEntityCfg
from .sensors import TerrainHeightSensor
ManagerBasedRlEnv = Entity = RewardTermCfg = ContactSensor = BuiltinSensor = Any
_DEFAULT_ASSET_CFG = SceneEntityCfg("robot")

'''
    (root / "velocity_rewards.py").write_text(
        template_header + "\n\n".join(ast.unparse(template_nodes[n]) for n in sorted(template_names)) + "\n"
    )

    out = {
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "velocity_rewards_sha256": hashlib.sha256(template_source.read_bytes()).hexdigest(),
        "tasks": {},
    }
    from examples.microduck.task_registry import task_key

    for task_id, c in configs.items():
        task = task_key(task_id)
        out["tasks"][task] = {
            "official_task_id": task_id,
            "episode_length_s": c.episode_length_s,
            "simulation": encode(c.sim),
            "decimation": c.decimation,
            "actions": encode(c.actions),
            "observations": encode(c.observations),
            "events": encode(c.events),
            "terminations": encode(c.terminations),
            "rewards": encode(c.rewards),
            "curricula": encode(c.curriculum),
            "commands": {
                name: encode(command) | {"adapter_command_class": type(command).__name__}
                for name, command in c.commands.items()
            },
            "terrain": encode(c.scene.terrain),
            "rl": encode(load_rl_cfg(task_id)),
        }
    snapshot_path = root / "configs/official_snapshot.json"
    # Preserve explicitly marked local shaping and command curricula during upstream refreshes.
    if snapshot_path.exists():
        previous = json.loads(snapshot_path.read_text())
        preserve_local_terms(out, previous)
    snapshot_path.write_text(json.dumps(out, indent=2) + "\n")

    # Formatting uses the parent project's pinned tool, independent of mjlab's environment.
    subprocess.run(
        [
            str(root.parents[1] / ".venv/bin/ruff"),
            "check",
            "--select",
            "I",
            "--fix",
            str(root / "velocity_rewards.py"),
            str(root / "reset_functions.py"),
        ],
        check=True,
    )
    subprocess.run(
        [
            str(root.parents[1] / ".venv/bin/ruff"),
            "format",
            "--line-length",
            "128",
            str(root / "reward_functions.py"),
            str(root / "velocity_rewards.py"),
            str(root / "reset_functions.py"),
        ],
        check=True,
    )


def export_terrains():
    import mujoco
    from mjlab.tasks.registry import load_env_cfg
    from mjlab.terrains.terrain_generator import TerrainGenerator

    root = Path(__file__).resolve().parent / "configs"
    for name, task in [("rough", "Mjlab-Velocity-Rough-MicroDuck"), ("slope", "Mjlab-RollerSlope-Flat-MicroDuck")]:
        cfg = load_env_cfg(task).scene.terrain.terrain_generator
        cfg.seed = 42
        spec = mujoco.MjSpec()
        generator = TerrainGenerator(cfg)
        generator.compile(spec)
        m = spec.compile()
        geoms = []
        for i in range(m.ngeom):
            g = {
                "type": int(m.geom_type[i]),
                "pos": m.geom_pos[i].tolist(),
                "quat": m.geom_quat[i].tolist(),
                "size": m.geom_size[i].tolist(),
            }
            if g["type"] == 1:
                j = m.geom_dataid[i]
                nr = int(m.hfield_nrow[j])
                nc = int(m.hfield_ncol[j])
                start = m.hfield_adr[j]
                g.update(
                    nrow=nr, ncol=nc, hsize=m.hfield_size[j].tolist(), data=m.hfield_data[start : start + nr * nc].tolist()
                )
            elif g["type"] != 6:
                raise ValueError(g["type"])
            geoms.append(g)
        (root / f"terrain_{name}.json").write_text(
            json.dumps({"seed": 42, "origins": generator.terrain_origins.tolist(), "geoms": geoms}, separators=(",", ":"))
            + "\n"
        )
        print(name, len(geoms))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", choices=("recipe", "terrain", "all"), nargs="?", default="recipe")
    args = parser.parse_args(argv)
    if args.target in ("recipe", "all"):
        export_recipe()
    if args.target in ("terrain", "all"):
        export_terrains()


if __name__ == "__main__":
    main()
